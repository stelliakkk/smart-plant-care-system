# 端口有没有被监听(也就是"这个服务是不是已经在跑了")
function Test-Listening([int]$Port) {
    return [bool](Get-NetTCPConnection -LocalPort $Port -State Listen -ErrorAction SilentlyContinue)
}

# 轮询等端口就绪, 避免服务还没起来就去开浏览器
function Wait-Listening([int]$Port, [int]$TimeoutSec = 60) {
    $sw = [System.Diagnostics.Stopwatch]::StartNew()
    while ($sw.Elapsed.TotalSeconds -lt $TimeoutSec) {
        if (Test-Listening $Port) { return $true }
        Start-Sleep -Milliseconds 400
    }
    return $false
}

# 读取当前实际连接的 WLAN；后端无法替 Windows 切 WiFi，所以必须先校验。
function Get-CurrentWifi {
    $lines = netsh wlan show interfaces 2>$null
    $name = $null
    $ssid = $null
    foreach ($line in $lines) {
        if ($line -match '^\s*Name\s*:\s*(.+)$') { $name = $Matches[1].Trim(); continue }
        if ($line -match '^\s*SSID\s*:\s*(.+)$') { $ssid = $Matches[1].Trim(); break }
    }
    if (-not $name -or -not $ssid) { return $null }
    return [pscustomobject]@{ Interface = $name; Ssid = $ssid }
}

# 只取当前 WiFi 网卡的 IPv4，避免 Docker、VPN 或虚拟网卡的地址被误用。
function Get-WifiLanIp([string]$InterfaceName) {
    $addresses = Get-NetIPAddress -InterfaceAlias $InterfaceName -AddressFamily IPv4 -ErrorAction SilentlyContinue |
        Where-Object { $_.IPAddress -notlike '169.254.*' -and $_.PrefixOrigin -ne 'WellKnown' }
    return $addresses | Select-Object -First 1 -ExpandProperty IPAddress
}

function Escape-CString([string]$Value) {
    return $Value.Replace('\', '\\').Replace('"', '\"')
}

function Write-GeneratedNetworkConfig([object]$Profile, [string]$ProfileName, [string]$LanIp) {
    $broker = "mqtt://${LanIp}:$brokerPort"
    $body = @(
        '/* Generated by scripts/start_dev.ps1. Do not edit: select a network and run again. */',
        '#pragma once',
        "#define ACTIVE_NETWORK_PROFILE `"$(Escape-CString $ProfileName)`"",
        "#define LOCAL_WIFI_SSID `"$(Escape-CString $Profile.ssid)`"",
        "#define LOCAL_WIFI_PASSWORD `"$(Escape-CString $Profile.password)`"",
        "#define LOCAL_MQTT_BROKER_URI `"$broker`""
    )
    foreach ($project in $edgeProjects) {
        $target = Join-Path $project 'main\generated_network_config.h'
        Set-Content -LiteralPath $target -Value $body -Encoding utf8
    }
    return $broker
}

# 每个服务开一个独立窗口: 标题标明用途, 日志实时可见, 关掉窗口就停掉服务。
#
# 为什么用 ProcessStartInfo 而不是 Start-Process:
#   Start-Process 会给"含空格的参数"自动补引号, 而我们的命令里本来就有引号
#   (路径带空格, 必须引号), 一补就变成嵌套引号, cmd 解析直接翻车。
#   ProcessStartInfo.Arguments 是原样交给系统的, 一个字符都不会被动, 最稳。
function Start-SvcWindow([string]$Title, [string]$WorkDir, [string]$CmdLine) {
    $psi = New-Object System.Diagnostics.ProcessStartInfo
    $psi.FileName         = 'cmd.exe'
    $psi.Arguments        = "/k title $Title && cd /d `"$WorkDir`" && $CmdLine"
    $psi.WorkingDirectory = $WorkDir
    $psi.UseShellExecute  = $true
    [void][System.Diagnostics.Process]::Start($psi)
}

function Write-Step([string]$Text) {
    Write-Host ''
    Write-Host "  $Text" -ForegroundColor Cyan
}

