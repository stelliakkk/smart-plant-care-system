#                          主流程
# ===============================================================

Write-Host ''
Write-Host '  =====================================================' -ForegroundColor DarkCyan
Write-Host '        植物养护系统 · 开发环境一键启动' -ForegroundColor Cyan
Write-Host '  =====================================================' -ForegroundColor DarkCyan

# ---------------------- 网络档案与边缘端配置 ----------------------
if (-not (Test-Path $networkProfilesFile)) {
    Write-Host "  X 找不到本机网络档案: $networkProfilesFile" -ForegroundColor Red
    Write-Host "    请复制模板后填写密码: Copy-Item '$networkProfilesExample' '$networkProfilesFile'" -ForegroundColor Yellow
    exit 1
}
try {
    $networkProfiles = Get-Content -LiteralPath $networkProfilesFile -Raw -Encoding UTF8 |
        ConvertFrom-Json -ErrorAction Stop
} catch {
    Write-Host "  X 网络档案 JSON 无法读取: $($_.Exception.Message)" -ForegroundColor Red
    exit 1
}
if (-not $NetworkProfile) {
    Write-Host ''
    Write-Host '  请选择本次要烧录给两块 ESP32 的网络:' -ForegroundColor Cyan
    $profileNames = @($networkProfiles.PSObject.Properties.Name)
    for ($i = 0; $i -lt $profileNames.Count; $i++) {
        $name = $profileNames[$i]
        $ssid = $networkProfiles.PSObject.Properties[$name].Value.ssid
        Write-Host ("    [{0}] {1} - {2}" -f ($i + 1), $name, $ssid)
    }
    $choice = (Read-Host '  输入编号或档案名称').Trim()
    if ($choice -match '^\d+$') {
        $index = [int]$choice - 1
        $NetworkProfile = if ($index -ge 0 -and $index -lt $profileNames.Count) {
            $profileNames[$index]
        } else { '' }
    } elseif ($networkProfiles.PSObject.Properties[$choice]) {
        $NetworkProfile = $choice
    } else {
        $NetworkProfile = ''
    }
}
if (-not $NetworkProfile -or -not $networkProfiles.PSObject.Properties[$NetworkProfile]) {
    Write-Host '  X 网络档案无效，启动已取消。' -ForegroundColor Red
    exit 1
}
$profile = $networkProfiles.PSObject.Properties[$NetworkProfile].Value
if (-not $profile.ssid -or -not $profile.password) {
    Write-Host "  X 档案 '$NetworkProfile' 未填写 SSID 或密码，启动已取消。" -ForegroundColor Red
    exit 1
}
$wifi = Get-CurrentWifi
if (-not $wifi) {
    Write-Host '  X 未检测到已连接的 WiFi；请先在 Windows 中连接目标网络。' -ForegroundColor Red
    exit 1
}
if ($wifi.Ssid -ne $profile.ssid) {
    Write-Host "  X 当前 WiFi 是 '$($wifi.Ssid)'，但选择的是 '$($profile.ssid)'。" -ForegroundColor Red
    Write-Host '    后端不能替 Windows 切换网络；请先切好 WiFi，再重新双击启动脚本。' -ForegroundColor Yellow
    exit 1
}
$lanIp = Get-WifiLanIp $wifi.Interface
if (-not $lanIp) {
    Write-Host "  X 未能从 WiFi 网卡 '$($wifi.Interface)' 取得 IPv4 地址，启动已取消。" -ForegroundColor Red
    exit 1
}
$brokerUri = Write-GeneratedNetworkConfig $profile $NetworkProfile $lanIp
Write-Host "  OK 网络档案: $NetworkProfile / $($profile.ssid)" -ForegroundColor Green
Write-Host "  OK 已生成两块 ESP32 的网络配置，MQTT: $brokerUri" -ForegroundColor Green

# ------------------------- [0] 环境自检 -------------------------
Write-Step '[0/4] 检查运行环境 ...'

if (-not (Test-Path $pyExe)) {
    Write-Host "  X 找不到后端虚拟环境: $pyExe" -ForegroundColor Red
    Write-Host '    补救: cd backend ; python -m venv .venv ; .venv\Scripts\pip install -r requirements.txt' -ForegroundColor Yellow
    exit 1
}
Write-Host "  OK Python  : $pyExe" -ForegroundColor Green

if (-not $nodeDir) {
    Write-Host '  X 没找到 Node 20 或更高版本，无法启动 Vite 6。' -ForegroundColor Red
    Write-Host "    已检查目录: $($nodeCandidates -join '; ')" -ForegroundColor Yellow
    Write-Host '    安装 Node 20+ 并加入 PATH 后，重新运行本脚本。' -ForegroundColor Yellow
    exit 1
}
$nodeVer = & (Join-Path $nodeDir 'node.exe') -v
Write-Host "  OK Node    : $nodeVer" -ForegroundColor Green

if (-not (Test-Path (Join-Path $frontend 'node_modules'))) {
    Write-Host '  X 前端依赖还没装' -ForegroundColor Red
    Write-Host "    补救: cd `"$frontend`" ; npm install --registry=https://registry.npmmirror.com" -ForegroundColor Yellow
    exit 1
}
Write-Host '  OK 前端依赖: 已安装' -ForegroundColor Green

# 让后面开出来的 cmd 窗口也优先用 Node 22
$env:PATH = "$nodeDir;$env:PATH"

# ------------------------- [1] MQTT broker -------------------------
if ($NoBroker) {
    Write-Step '[1/4] MQTT broker: 已跳过 (-NoBroker)'
}
elseif (Test-Listening $brokerPort) {
    Write-Step "[1/4] MQTT broker: 端口 $brokerPort 已在运行, 跳过"
}
else {
    Write-Step "[1/4] 启动 MQTT broker (监听 0.0.0.0:$brokerPort) ..."
    Start-SvcWindow "[1] MQTT Broker :$brokerPort" $backend `
        "`"$pyExe`" scripts\dev_broker.py --host 0.0.0.0 --port $brokerPort"
    if (Wait-Listening $brokerPort 25) {
        Write-Host "  OK broker 已就绪 (板子连 mqtt://<本机IP>:$brokerPort)" -ForegroundColor Green
    }
    else {
        Write-Host '  !! broker 没起来, 看 [1] 那个窗口的报错' -ForegroundColor Yellow
    }
}

# ------------------------- [2] 后端 -------------------------
if (Test-Listening $backendPort) {
    Write-Step "[2/4] 后端: 端口 $backendPort 已在运行, 跳过"
}
else {
    Write-Step "[2/4] 启动后端 uvicorn (127.0.0.1:$backendPort) ..."
    Start-SvcWindow "[2] Backend :$backendPort" $backend `
        "`"$pyExe`" -m uvicorn app.main:app --host 127.0.0.1 --port $backendPort"
    if (Wait-Listening $backendPort 45) {
        Write-Host '  OK 后端已就绪' -ForegroundColor Green
    }
    else {
        Write-Host '  !! 后端没起来, 看 [2] 那个窗口(常见: 依赖没装 / 端口被占)' -ForegroundColor Yellow
    }
}

# ------------------------- [3] 模拟设备(可选) -------------------------
if ($WithSim) {
    Write-Step '[3/4] 启动模拟设备 (每 3 秒造一条数据) ...'
    Start-SvcWindow '[4] Sim Device' $backend `
        "`"$pyExe`" scripts\sim_device.py --host 127.0.0.1 --port $brokerPort --interval 3"
    Start-Sleep -Seconds 2
}
else {
    Write-Step '[3/4] 模拟设备: 未启用 (加 -WithSim 可让没硬件时也有数据)'
}

# ------------------------- [4] 前端 -------------------------
if (Test-Listening $frontendPort) {
    Write-Step "[4/4] 前端: 端口 $frontendPort 已在运行, 跳过"
}
else {
    Write-Step "[4/4] 启动前端 Vite ($frontendPort) ..."
    Start-SvcWindow "[3] Frontend :$frontendPort" $frontend 'npm run dev'
    if (Wait-Listening $frontendPort 90) {
        Write-Host '  OK 前端已就绪' -ForegroundColor Green
    }
    else {
        Write-Host '  !! 前端没起来, 看 [3] 那个窗口的报错' -ForegroundColor Yellow
    }
}

