<#
=====================================================================
  一键启动开发环境 —— MQTT broker + 后端 + 前端
=====================================================================
用法:
    在 pro\ 目录里双击 start_dev.bat (推荐), 或者手动运行:
        powershell -ExecutionPolicy Bypass -File scripts\start_dev.ps1

参数:
    -NoBroker    不起 MQTT broker (只调前端样式时用, 少一个窗口)
    -WithSim     额外起一个"模拟设备", 没有硬件时页面也有数据在跳
    -NoBrowser   不自动打开浏览器
    -NetworkProfile <name>  跳过菜单，指定本次要生成给边缘端的网络档案

它替你做掉的三件烦事:
    1) 自动找到 Node 22 —— PATH 里的 node 是 v18, Vite 6 根本跑不起来
    2) 检查 .venv / node_modules 是否就绪, 缺什么直接说清楚怎么补
    3) MQTT broker 用 0.0.0.0 启动 —— 否则 ESP32 板子永远连不上
=====================================================================
