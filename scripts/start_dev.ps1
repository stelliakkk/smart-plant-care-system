$backend  = Join-Path $root 'backend'
$frontend = Join-Path $root 'frontend'
$pyExe    = Join-Path $backend '.venv\Scripts\python.exe'
$networkProfilesFile = Join-Path $PSScriptRoot 'network_profiles.local.json'
$networkProfilesExample = Join-Path $PSScriptRoot 'network_profiles.local.example.json'
