Write-Host "          $url" -ForegroundColor Yellow
Write-Host ''
if ($lanIp) {
    Write-Host "   手机/平板(需同一个 WiFi): http://${lanIp}:$frontendPort" -ForegroundColor DarkGray
    if (-not $NoBroker) {
        Write-Host "   ESP32 要连的 broker     : mqtt://${lanIp}:$brokerPort" -ForegroundColor DarkGray
    }
}
Write-Host "   后端接口文档            : http://127.0.0.1:$backendPort/docs" -ForegroundColor DarkGray
Write-Host ''
Write-Host '   下一步：请重新编译并烧录两块板（网络已写入待编译配置）:' -ForegroundColor Yellow
Write-Host '   1) edge\esp32s3_plant_edge     → idf.py -p COMx build flash' -ForegroundColor DarkGray
