    $nodeCandidates += Split-Path -Parent $pathNode.Source
}
$nodeCandidates = @($nodeCandidates | Select-Object -Unique)
foreach ($d in $nodeCandidates) {
    $candidateNode = Join-Path $d 'node.exe'
    if (-not (Test-Path $candidateNode)) { continue }
    $candidateVersion = & $candidateNode --version
    if ($candidateVersion -match '^v?(\d+)\.' -and [int]$Matches[1] -ge 20) {
        $nodeDir = $d
        break
    }
}

