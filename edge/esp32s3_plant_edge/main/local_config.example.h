/* ------------------- 土壤探头标定 (单位 mV) -------------------
 * 电容式探头: 越干电压越高, 越湿电压越低。
 * 下面给的是"常见电容式探头"的公开经验值:
 *     空气中约 2.6V, 浸入水中约 1.2V
 *   (来源: DFRobot SEN0193 规格书 —— 供电 3.3~5.5V, 输出 0~3.0V;
 *          常见的电容式 v1.2 教程 —— 电压范围约 1.2V~3.0V)
 *
 * 但这只是起点: 不同批次探头能差几百 mV, 想准还是得自己标 ——
 *   1) 烧录后看串口, 探头悬空在空气中, 记下 voltage_mv
 *   2) 探头泡进一杯清水, 记下 voltage_mv
 *   3) 分别填到下面两行, 重新 idf.py -p COM3 flash
 * 判断标准: 悬空应显示约 0%, 泡水应显示约 100%。
 * 详细步骤见 pro/docs/hardware_wiring.md。 */
#define LOCAL_SOIL_MV_DRY        2600
#define LOCAL_SOIL_MV_WET        1200
